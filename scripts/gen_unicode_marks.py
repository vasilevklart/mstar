#!/usr/bin/env python3
"""Write the combining-mark table both speech frontends read, from this
interpreter's ``unicodedata``: ``rust/server/src/unicode_marks.rs`` and its
Python copy, ``mstar/api_server/openai/unicode_marks.py``.

The two frontends have to split text in exactly the same place, and
``speech_chunking`` steps a cut back off a combining mark (a character of
category ``M*``). Neither can ask a Unicode database of its own: Rust's
``regex`` crate carries tables that move with the crate, and Python's
``unicodedata`` moves with CPython (3.14 carries UCD 16.0.0, which makes 51
more code points marks, U+0897 among them). So both read the one table this
writes, and they agree on every Python.

The table holds the marks of UCD 15.0.0, written from CPython 3.12 (3.13
carries 15.1.0, which has the same marks). Moving it to a newer Unicode is a
choice, not something a CPython upgrade forces: run this from an interpreter
that carries that version::

    python scripts/gen_unicode_marks.py

``test/modular/test_speech_chunking.py`` checks that the two files hold the
same code points and are what this writes, and, on an interpreter that carries
the table's Unicode version, that they hold its marks. Regenerating with a
different mark set also moves the cases pinned to U+0897, in
``speech_chunking.rs`` and in that test.
"""

from __future__ import annotations

import sys
import unicodedata
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
RUST_TABLE = REPO / "rust/server/src/unicode_marks.rs"
PY_TABLE = REPO / "mstar/api_server/openai/unicode_marks.py"
PER_LINE = 4

RUST_HEADER = """\
// @generated by scripts/gen_unicode_marks.py. Do not edit.
//
// The code points CPython's `unicodedata` calls combining marks, as inclusive
// ranges, sorted and neither overlapping nor adjacent. `speech_chunking` reads
// them so that the Rust frontend cuts long text where the Python one does;
// `regex`'s `\\p{M}` carries the crate's own Unicode tables instead of the
// interpreter's, which is the same question asked of a different version.
//
// Regenerate with `python scripts/gen_unicode_marks.py` and say so in the
// commit: the cut points of text holding the affected code points move with it.
"""

PY_HEADER = """\
# @generated by scripts/gen_unicode_marks.py. Do not edit.
#
# The code points CPython's `unicodedata` calls combining marks in the Unicode
# version below, as inclusive ranges, sorted and neither overlapping nor
# adjacent: the table rust/server/src/unicode_marks.rs holds. `speech_chunking`
# reads it instead of the running interpreter's `unicodedata`, whose Unicode
# version moves with CPython, so that the Python frontend cuts long text where
# the Rust one does on every Python.
#
# Regenerate with `python scripts/gen_unicode_marks.py` and say so in the
# commit: the cut points of text holding the affected code points move with it.
"""


def mark_ranges() -> list[tuple[int, int]]:
    """Every code point of category ``M*``, as inclusive ranges."""
    ranges: list[tuple[int, int]] = []
    for code in range(sys.maxunicode + 1):
        if not unicodedata.category(chr(code)).startswith("M"):
            continue
        if ranges and ranges[-1][1] == code - 1:
            ranges[-1] = (ranges[-1][0], code)
        else:
            ranges.append((code, code))
    return ranges


def _rows(ranges: list[tuple[int, int]]) -> str:
    """``ranges`` as indented lines of ``PER_LINE`` pairs, the same in both languages."""
    pairs = [f"(0x{low:04x}, 0x{high:04x})," for low, high in ranges]
    return "\n".join(
        "    " + " ".join(pairs[i:i + PER_LINE]).rstrip()
        for i in range(0, len(pairs), PER_LINE)
    )


def _summary(ranges: list[tuple[int, int]]) -> str:
    total = sum(high - low + 1 for low, high in ranges)
    return f"{total} code points in {len(ranges)} ranges"


def render_rust(ranges: list[tuple[int, int]]) -> str:
    """The Rust source for ``ranges``."""
    return (
        f"{RUST_HEADER}\n"
        f"/// {_summary(ranges)}.\n"
        "pub const MARK_RANGES: &[(u32, u32)] = &[\n" + _rows(ranges) + "\n];\n"
    )


def render_python(ranges: list[tuple[int, int]], unidata_version: str) -> str:
    """The Python source for ``ranges``, the marks of UCD ``unidata_version``."""
    return (
        f"{PY_HEADER}\n"
        f'UNIDATA_VERSION = "{unidata_version}"\n\n'
        f"# {_summary(ranges)}.\n"
        "MARK_RANGES: tuple[tuple[int, int], ...] = (\n" + _rows(ranges) + "\n)\n"
    )


def main() -> None:
    ranges = mark_ranges()
    RUST_TABLE.write_text(render_rust(ranges))
    PY_TABLE.write_text(render_python(ranges, unicodedata.unidata_version))
    for table in (RUST_TABLE, PY_TABLE):
        print(f"{table}: {_summary(ranges)} (UCD {unicodedata.unidata_version})")


if __name__ == "__main__":
    main()
